#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
//
// Walks <repo>/<category>/<name>/registry.entry.yaml files and emits a single
// registry.yaml at the repo root.
//
// Run from the repo root:
//   node scripts/build-registry.js
//
// Re-run after adding or modifying integrations.

const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");

const REPO_ROOT = path.resolve(__dirname, "..");

const SKIP_DIRS = new Set([".github", "_examples", "docs", "scripts"]);

function walkCategories(root) {
  return fs
    .readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !SKIP_DIRS.has(d.name) && !d.name.startsWith("."))
    .map((d) => d.name)
    .sort();
}

function walkIntegrations(categoryDir) {
  return fs
    .readdirSync(categoryDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
}

function loadEntry(integrationDir, fallback) {
  const entryPath = path.join(integrationDir, "registry.entry.yaml");
  if (!fs.existsSync(entryPath)) {
    return { ...fallback, status: "stub" };
  }
  const raw = fs.readFileSync(entryPath, "utf8");
  try {
    const parsed = yaml.load(raw);
    return { ...fallback, ...parsed };
  } catch (err) {
    console.error(`! Failed to parse ${entryPath}: ${err.message}`);
    return { ...fallback, status: "stub" };
  }
}

const entries = [];

for (const category of walkCategories(REPO_ROOT)) {
  const categoryDir = path.join(REPO_ROOT, category);
  for (const name of walkIntegrations(categoryDir)) {
    const integrationDir = path.join(categoryDir, name);
    const fallback = {
      name,
      displayName: name,
      category,
      path: `${category}/${name}`,
      maintainedBy: "Community contributors",
      type: "scaffold",
      description: "(no registry.entry.yaml — needs metadata)",
      status: "stub",
    };
    entries.push(loadEntry(integrationDir, fallback));
  }
}

const generated = new Date().toISOString().replace(/\.\d+Z$/, "Z");
const header = `# Ory Integrations Registry
#
# Single source of truth for integrations in this repository.
# Generated by scripts/build-registry.js — do not edit by hand. To update,
# edit the per-integration registry.entry.yaml file and re-run the generator.

apiVersion: ory.com/integrations-v1
kind: Registry
metadata:
  name: ory-integrates
  generated: ${generated}
integrations:
`;

const body = yaml.dump(entries, { indent: 2, lineWidth: 120, noRefs: true, sortKeys: false });
const indented = body
  .split("\n")
  .map((l) => (l.length ? `  ${l}` : l))
  .join("\n");

const outPath = path.join(REPO_ROOT, "registry.yaml");
fs.writeFileSync(outPath, header + indented);

const byType = {};
const byMaintainer = {};
for (const e of entries) {
  byType[e.type] = (byType[e.type] || 0) + 1;
  byMaintainer[e.maintainedBy] = (byMaintainer[e.maintainedBy] || 0) + 1;
}
console.log(`Wrote ${entries.length} entries to ${outPath}`);
console.log(`By type:       ${JSON.stringify(byType)}`);
console.log(`By maintainer: ${JSON.stringify(byMaintainer)}`);
